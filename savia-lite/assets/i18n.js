export function createTranslator(language) {
  const table = STRINGS[language] || STRINGS.es;
  const fallback = STRINGS.es;
  return function t(key, vars) {
    let text = table[key] ?? fallback[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };
}

/** Sanity aid used by tools/selfcheck.mjs - every language must cover every key. */
export function translationKeys() {
  return Object.fromEntries(Object.entries(STRINGS).map(([code, table]) => [code, Object.keys(table).sort()]));
}
