export const translationKeys = (code) => Object.keys(STRINGS[code] || {});

/**
 * Returns a translator. Unknown keys return the key itself so a gap is loud
 * in the interface instead of silently rendering an empty string.
 */
export function createTranslator(code) {
  const table = STRINGS[code] || STRINGS.es;
  return function t(key, vars) {
    let text = table[key];
    if (text === undefined) return key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };
}
