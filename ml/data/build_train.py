def main() -> None:
    rows = []
    for label, groups in {
        "inquiry": [("es", INQUIRY_ES), ("pt", INQUIRY_PT)],
        "dispute": [("es", DISPUTE_ES), ("pt", DISPUTE_PT)],
        "human":   [("es", HUMAN_ES), ("pt", HUMAN_PT)],
        "other":   [("es", OTHER_ES), ("pt", OTHER_PT)],
    }.items():
        for lang, texts in groups:
            rows += [{"text": t, "label": label, "lang": lang, "author": AUTHOR} for t in texts]
    seen = set()
    for r in rows:
        key = r["text"].strip().lower()
        assert key not in seen, f"duplicate: {r['text']}"
        seen.add(key)
    out = Path(__file__).with_name("router_train.csv")
    with out.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["text", "label", "lang", "author"])
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {out} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
