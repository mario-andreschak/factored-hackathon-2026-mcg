import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
export const HEAD = 'c44d416fcf1ab95bcb16c77651418e6570d79782';
export const PORTAL_HEAD = '634aa5244374b3e105ef7864fa100530bab45ec2';
export const CONTEXT = 'C:/Users/Moe/.codex/tmp/savia-ui-runtime-c44d416fcf1a';
export const DESCRIPTOR_SHA = '3d200c1f58957b3b3a032dbde642633e6c34eee70c7bee26734cdf0e1d137dd9';
export const sha = data => createHash('sha256').update(data).digest('hex');
export async function validateBinding(bindingPath) {
  const cfg = JSON.parse(await fs.readFile(path.resolve(bindingPath), 'utf8'));
  assert.equal(cfg.schema, 'savia-ack-pt-continuation-native-binding/v1');
  assert.equal(cfg.root_go, true); assert.equal(cfg.frozen_cohort_complete, true);
  assert.equal(cfg.generated_only, true); assert.equal(cfg.frozen_healthy, true);
  assert.equal(cfg.native_result_mode, 'native_exact');
  assert.equal(cfg.authorization.approved_source_revision, HEAD);
  assert.match(cfg.authorization.approved_image_digest, /^sha256:[a-f0-9]{64}$/);
  assert.equal(cfg.runtime.git_head, HEAD);
  assert.equal(cfg.runtime.image_digest, cfg.authorization.approved_image_digest);
  assert.equal(cfg.base_url, 'https://savia-rc-2026.fly.dev');
  assert.deepEqual(cfg.cases, [{language:'pt',profile:'colombia'}]);
  assert.equal(path.resolve(cfg.expected_ui_runtime_path), path.resolve(CONTEXT, 'expected-ui-runtime.json'));
  const descriptorBytes = await fs.readFile(cfg.expected_ui_runtime_path);
  assert.equal(sha(descriptorBytes), DESCRIPTOR_SHA); assert.equal(cfg.expected_ui_runtime_sha256, DESCRIPTOR_SHA);
  const expected = JSON.parse(descriptorBytes);
  assert.equal(expected.final_head, HEAD); assert.equal(expected.portal_head, PORTAL_HEAD);
  assert.equal(expected.final_tree, 'fabf02d622f51302e229137405e3607356d00ab0');
  assert.equal(cfg.runtime.git_tree,expected.final_tree);
  assert.equal(Object.keys(expected.new_sources).length,183); assert.equal(Object.keys(expected.new_browser).length,21);
  assert.equal(Object.keys(expected.native).length,4); assert.equal(Object.keys(expected.portal).length,28);
  assert.equal(Object.keys(expected.retained_pitch_media).length,16);
  assert.deepEqual(cfg.runtime.served_ui, expected.new_browser);
  assert.equal(cfg.runtime.browser_source, HEAD); assert.equal(cfg.runtime.portal_source, PORTAL_HEAD);
  assert.equal(cfg.runtime.source_manifest_sha256, expected.final_source_manifest_sha256);
  const proofBytes = await fs.readFile(cfg.runtime_proof_path);
  assert.equal(sha(proofBytes), cfg.runtime_proof_sha256);
  const proof = JSON.parse(proofBytes);
  assert.equal(proof.schema,'savia-ack-successor-runtime/v1'); assert.equal(proof.application_source,HEAD);
  assert.equal(proof.git_tree,expected.final_tree); assert.equal(proof.manifest.git_tree,expected.final_tree);
  assert.equal(proof.portal_source,PORTAL_HEAD);
  assert.equal(proof.image,'registry.fly.io/savia-rc-2026@'+cfg.authorization.approved_image_digest);
  assert.equal(proof.expected_descriptor_sha256,DESCRIPTOR_SHA);
  assert.equal(proof.source_manifest_sha256,expected.final_source_manifest_sha256);
  assert.deepEqual(proof.source_hashes,expected.new_sources); assert.deepEqual(proof.served_ui,expected.new_browser);
  assert.deepEqual(proof.retained_runtime_hashes,expected.native); assert.deepEqual(proof.portal_hashes,expected.portal);
  assert.deepEqual(proof.retained_pitch_media_hashes,expected.retained_pitch_media);
  assert.equal(proof.fresh_browser_verified,true); assert.equal(proof.preserved_native_runtime,true);
  assert.equal(proof.preserved_machine_configuration,true); assert.equal(proof.machine_state,'started');
  assert.equal(cfg.runtime.reverified_at_utc,proof.reverified_at_utc);
  assert.equal(path.resolve(cfg.runtime_proof_path),path.resolve(CONTEXT,'runtime-verification.json'));
  assert.equal(path.resolve(cfg.public_assets_proof_path),path.resolve(CONTEXT,'public-assets-verification.json'));
  const publicBytes=await fs.readFile(cfg.public_assets_proof_path);
  assert.equal(sha(publicBytes),cfg.public_assets_proof_sha256);
  const publicProof=JSON.parse(publicBytes);
  assert.equal(publicProof.schema,'savia-ack-successor-public-assets/v1');
  assert.equal(publicProof.application_source,HEAD); assert.equal(publicProof.portal_source,PORTAL_HEAD);
  assert.equal(publicProof.image,proof.image); assert.equal(publicProof.expected_descriptor_sha256,DESCRIPTOR_SHA);
  assert.equal(publicProof.verified_public_assets,27); assert.equal(publicProof.health,200);
  assert.equal(publicProof.entry_gateway,200); assert.equal(publicProof.anonymous_api,401);
  assert.equal(publicProof.internal_manifest,404);
  const at=Date.parse(proof.reverified_at_utc);
  assert(Number.isFinite(at)&&at<=Date.now()+30000&&Date.now()-at<=900000,'Fresh runtime proof within15 minutes required');
  assert.equal(sha(await fs.readFile(new URL(import.meta.url))),cfg.binding_gate_sha256);
  const priorPath='C:/Users/Moe/.codex/tmp/savia-ack-successor-native-private-c44d416fcf1a/2026-10-06T01-48-18-527Z/receipt-private.json';
  const priorSha='67c436c315c0bb729ff5c68bc3d6919cea9eb5c5076d5a410f044e4960bd5c9e';
  assert.equal(cfg.prior_es_attempt_sha256,priorSha);
  assert.equal(cfg.authorization.approved_prior_es_attempt_sha256,priorSha);
  assert.equal(path.resolve(cfg.prior_es_attempt_path),path.resolve(priorPath));
  const priorBytes=await fs.readFile(priorPath); assert.equal(sha(priorBytes),priorSha);
  const prior=JSON.parse(priorBytes);
  assert.equal(prior.passed,false); assert.equal(prior.cases.length,1);
  assert.equal(prior.observedProviderEligibleResultRequests,1); assert.equal(prior.actualUIPlayedAcks,1);
  assert.equal(prior.observedNegativeResultRequests,1);
  assert.equal(prior.runtime.git_head,HEAD); assert.equal(prior.runtime.image_digest,cfg.runtime.image_digest);
  assert.equal(prior.runtime.source_manifest_sha256,expected.final_source_manifest_sha256);
  assert.equal(prior.runtime.expected_ui_runtime_sha256,DESCRIPTOR_SHA);
  const es=prior.cases[0]; assert.equal(es.language,'es'); assert.equal(es.fictionalProfile,'mexico'); assert.equal(es.passed,true);
  assert.equal(es.uiGuidancePlayback.strictHostCaptionEquality,true);
  assert.equal(es.uiGuidancePlayback.actualHostReply,es.uiGuidancePlayback.actualNativeCaption);
  assert.equal(es.uiGuidancePlayback.actualUIResultInputEqualToHostReply,true);
  assert.equal(es.uiGuidancePlayback.transportProtocolAccepted,true); assert.equal(es.uiGuidancePlayback.caveatPresentInCaption,true);
  assert.equal(es.uiGuidancePlayback.sampleRate,24000); assert.equal(es.uiGuidancePlayback.samples,399600);
  const ack=es.uiGuidancePlayback.actualUIAck; assert.equal(ack.httpStatus,200); assert.equal(ack.complete,true);
  assert.equal(ack.playedSamples,399600); assert.equal(ack.exactSamples,true); assert.equal(ack.afterStreamCompletion,true);
  assert.equal(ack.emittedByProductUI,true); assert.equal(ack.noHarnessAckInjection,true);
  assert.equal(es.existingCardProtection.savedReceiptUnchanged,true); assert.equal(es.existingCardProtection.newPrepareConfirmCancelRequests,0);
  assert.equal(es.negativeTamperedResult.httpStatus,409); assert.equal(es.negativeTamperedResult.providerEligible,false);
  return {cfg,expected,proof};
}
